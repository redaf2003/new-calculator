func Proverka1() {

	number := 0 // Глобальная переменная в функции main
	// Пример использования цикла for для вывода чисел от 1 до 5
	//i := 1 // Инициализация переменной цикла
	//i <= 5 // Условие продолжения цикла , текст должен выводиться 5 раз
	//i++   // Инкремент переменной цикла (увеличение на 1)
	// переменная i существует только внутри цикла for , после выхода из цикла она недоступна , поэтому попытка обращения к ней вызовет ошибку компиляции
	for i := 1; i <= 5; i++ {
		score := 5                                                             //можем положить внутрь цикла и удлаяется в конце каждой итерации
		score += 3                                                             //увеличиваем score на 3 при каждой итерации цикла
		fmt.Println("Число:", i, "Оценка:", score, "Значение number:", number) // number доступна здесь , так как объявлена вне цикла for а в main
		number++                                                               // увеличиваем number на 1 при каждой итерации цикла
		//score := 5 - тут она удаляется в конце каждой итерации

	}
	fmt.Println(number) // number доступна здесь , так как объявлена вне цикла for а в main
	//fmt.Println("Число:") // здесь i уже не существует

	//i = 5 // Ошибка: переменная i не определена в этой области видимости (ДОСТУПНА ТОЛЬКО ВНУТРИ ЦИКЛА FOR)
}

