func Proverka4() {

	score := 0
	fmt.Println("")
	fmt.Println("Изначально ваш счет:", score)
	fmt.Println("")
	number := 0

	for {
		fmt.Println("Подлетел к трубе:", number)
		fmt.Println("Пролетел трубу:", number)
		fmt.Println("Ваш счет:", score)
		fmt.Println("")
		number++
		score++
		if rand.Intn(10) == 1 { // если рандомное число равно 1 (шанс 1 из 10) , то игрок врезается в трубу
			fmt.Println("Бля я врезался в трубу:", number-1)
			break // выходим из цикла
			//fmt.Println("Итоговый счет:", score)
		}

		//	fmt.Println("итоговый счет", score)
		time.Sleep(500 * time.Millisecond)

	}
	fmt.Println("")
	fmt.Println("Игра закончена!!!", "Итоговый счет:", score-1)
	fmt.Println("")
}
